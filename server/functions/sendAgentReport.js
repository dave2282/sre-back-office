// Ported from base44/functions/sendAgentReport/entry.ts

export default async (req, base44) => {
  const user = await base44.auth.me();
  if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });

  const { agentName, agentEmail, rangeLabel, stats, breakdown, brokerageName } = await req.json();

  if (!agentEmail) return Response.json({ error: 'agentEmail is required' }, { status: 400 });

  const fmt$ = (n) => '$' + (n || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

  const sideRows = (breakdown || []).map(b => `
    <tr>
      <td style="padding:8px 12px; color:#6b7280; padding-left:24px;">${b.side}</td>
      <td style="padding:8px 12px; text-align:right;">${b.count}</td>
      <td style="padding:8px 12px; text-align:right;">${fmt$(b.volume)}</td>
      <td style="padding:8px 12px; text-align:right;">${fmt$(b.officeComm)}</td>
      <td style="padding:8px 12px; text-align:right;">${fmt$(b.agentNet)}</td>
    </tr>`).join('');

  const html = `
  <div style="font-family: sans-serif; max-width: 640px; margin: 0 auto; color: #1f2937;">
    <div style="background: #1e293b; color: white; padding: 28px 32px; border-radius: 12px 12px 0 0;">
      <h1 style="margin:0; font-size:22px;">${brokerageName || 'Brokerage'}</h1>
      <p style="margin:6px 0 0; opacity:0.7; font-size:14px;">Production Report — ${rangeLabel}</p>
    </div>
    <div style="background:#f8fafc; padding:28px 32px; border-radius: 0 0 12px 12px; border: 1px solid #e2e8f0; border-top: none;">
      <p style="margin:0 0 20px; font-size:15px;">Hi <strong>${agentName}</strong>,</p>
      <p style="margin:0 0 20px; font-size:14px; color:#6b7280;">Here is your production summary for <strong>${rangeLabel}</strong>.</p>

      <table style="width:100%; border-collapse:collapse; background:white; border-radius:8px; overflow:hidden; border:1px solid #e2e8f0; margin-bottom:20px;">
        <thead>
          <tr style="background:#f1f5f9;">
            <th style="padding:10px 12px; text-align:left; font-size:12px; color:#6b7280; text-transform:uppercase; letter-spacing:.05em;">Category</th>
            <th style="padding:10px 12px; text-align:right; font-size:12px; color:#6b7280; text-transform:uppercase; letter-spacing:.05em;">Deals</th>
            <th style="padding:10px 12px; text-align:right; font-size:12px; color:#6b7280; text-transform:uppercase; letter-spacing:.05em;">Volume</th>
            <th style="padding:10px 12px; text-align:right; font-size:12px; color:#6b7280; text-transform:uppercase; letter-spacing:.05em;">Office Comm</th>
            <th style="padding:10px 12px; text-align:right; font-size:12px; color:#6b7280; text-transform:uppercase; letter-spacing:.05em;">Agent Net</th>
          </tr>
        </thead>
        <tbody>
          <tr style="background:#f0fdf4; font-weight:600;">
            <td style="padding:10px 12px; color:#166534;">TOTAL</td>
            <td style="padding:10px 12px; text-align:right;">${stats.count}</td>
            <td style="padding:10px 12px; text-align:right;">${fmt$(stats.volume)}</td>
            <td style="padding:10px 12px; text-align:right; color:#15803d;">${fmt$(stats.officeComm)}</td>
            <td style="padding:10px 12px; text-align:right;">${fmt$(stats.agentNet)}</td>
          </tr>
          ${sideRows}
        </tbody>
      </table>

      <p style="margin:0; font-size:13px; color:#9ca3af;">This report was generated by ${brokerageName || 'your brokerage'} and sent to ${agentEmail}.</p>
    </div>
  </div>`;

  await base44.asServiceRole.integrations.Core.SendEmail({
    to: agentEmail,
    subject: `Your Production Report — ${rangeLabel}`,
    body: html,
    from_name: brokerageName || 'Brokerage Reports',
  });

  return Response.json({ success: true });
};
